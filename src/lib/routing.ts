// Transit-time calculation.
// Ground modes use OSRM (OpenStreetMap's free routing engine — no API key, unlike Google Maps).
// Airplane mode does not use road routing: it uses the departure/arrival difference when available,
// otherwise a great-circle flight estimate.
import { modeIcon } from './transportModes'

export const isFlight = (mode: string) => /air|flight|plane|fly/i.test(mode || '')

export interface LatLng { lat: number; lng: number }

/**
 * Shortest-path (great-circle) points between two places, e.g. SEA -> HND goes
 * west across the Pacific instead of the long way east over Europe/Asia.
 * Points are generated by spherical interpolation; longitudes are normalized
 * to [-180, 180], so consecutive points may jump across the antimeridian —
 * the map layer splits the line there instead of drawing across the whole world.
 */
export function greatCirclePath(from: LatLng, to: LatLng, steps = 72): LatLng[] {
  const toVec = (p: LatLng) => {
    const lat = p.lat * Math.PI / 180, lng = p.lng * Math.PI / 180
    return { x: Math.cos(lat) * Math.cos(lng), y: Math.cos(lat) * Math.sin(lng), z: Math.sin(lat) }
  }
  const a = toVec(from), b = toVec(to)
  const dot = Math.min(1, Math.max(-1, a.x * b.x + a.y * b.y + a.z * b.z))
  const angle = Math.acos(dot)
  if (angle < 1e-6) return [from, to]
  const sin = Math.sin(angle)
  const pts: LatLng[] = []
  for (let i = 0; i <= steps; i++) {
    const t = i / steps
    const k1 = Math.sin((1 - t) * angle) / sin, k2 = Math.sin(t * angle) / sin
    const x = a.x * k1 + b.x * k2, y = a.y * k1 + b.y * k2, z = a.z * k1 + b.z * k2
    const lat = Math.atan2(z, Math.sqrt(x * x + y * y)) * 180 / Math.PI
    let lng = Math.atan2(y, x) * 180 / Math.PI
    if (lng > 180) lng -= 360; if (lng < -180) lng += 360
    pts.push({ lat, lng })
  }
  return pts
}

export function haversineKm(a: LatLng, b: LatLng): number {
  const R = 6371, dLat = (b.lat - a.lat) * Math.PI / 180, dLng = (b.lng - a.lng) * Math.PI / 180
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * Math.PI / 180) * Math.cos(b.lat * Math.PI / 180) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}

export async function calculateTransitMinutes(from: LatLng | null, to: LatLng | null, mode: string, startAt?: string, endAt?: string): Promise<{ minutes: number; source: string } | null> {
  if (isFlight(mode)) {
    if (startAt && endAt) {
      const diff = Math.round((+new Date(endAt) - +new Date(startAt)) / 60000)
      if (diff > 0) return { minutes: diff, source: 'from departure/arrival times' }
    }
    if (from && to) {
      const km = haversineKm(from, to)
      return { minutes: Math.max(20, Math.round(km / 750 * 60) + 30), source: 'estimated flight time (distance)' }
    }
    return null
  }
  if (from && to) {
    try {
      const quickest = await getQuickestRoute(from, to, mode)
      if (quickest) return { minutes: quickest.minutes, source: quickest.source }
    } catch { /* fall through to estimate */ }
    const km = haversineKm(from, to)
    return { minutes: Math.max(5, Math.round(km / 50 * 60)), source: 'estimated from distance' }
  }
  if (startAt && endAt) {
    const diff = Math.round((+new Date(endAt) - +new Date(startAt)) / 60000)
    if (diff > 0) return { minutes: diff, source: 'from departure/arrival times' }
  }
  return null
}

export interface RouteResult { minutes: number; distanceKm: number; path: LatLng[]; source: string }

/**
 * Quickest route between two stops.
 * Ground modes: asks OSRM for up to 3 alternative routes and picks the one with the
 * shortest duration; `path` is that route's real road geometry so the map can draw it.
 * Airplane: the "route" is a direct line (great-circle), timed by flight estimate.
 */
export async function getQuickestRoute(from: LatLng, to: LatLng, mode: string): Promise<RouteResult | null> {
  if (isFlight(mode)) {
    const km = haversineKm(from, to)
    return { minutes: Math.max(20, Math.round(km / 750 * 60) + 30), distanceKm: km, path: greatCirclePath(from, to), source: 'shortest flight route (great-circle, estimated time)' }
  }
  if (/train|rail/i.test(mode || '')) {
    const km = haversineKm(from, to)
    return { minutes: Math.max(15, Math.round(km / 90 * 60) + 10), distanceKm: km, path: greatCirclePath(from, to, 24), source: 'rail estimate' }
  }
  try {
    const profile = /walk|foot/i.test(mode || '')
      ? 'foot'
      : /bike|cycl/i.test(mode || '')
        ? 'bike'
        : 'driving'
    const url = `https://router.project-osrm.org/route/v1/${profile}/${from.lng},${from.lat};${to.lng},${to.lat}?overview=full&geometries=geojson&alternatives=3&steps=false`
    const r = await fetch(url)
    const j = await r.json()
    const routes: any[] = j?.routes ?? []
    if (routes.length) {
      const quickest = routes.reduce((best, rt) => (rt.duration < best.duration ? rt : best), routes[0])
      const coords: [number, number][] = quickest.geometry?.coordinates ?? []
      const path = coords.map(([lng, lat]) => ({ lat, lng }))
      const label = profile === 'foot' ? 'walking route (OSRM)' : 'quickest route calculated with OpenStreetMap (OSRM)'
      return { minutes: Math.round(quickest.duration / 60), distanceKm: (quickest.distance ?? 0) / 1000, path: path.length > 1 ? path : [from, to], source: label }
    }
  } catch { /* fall through */ }
  if (/walk|foot/i.test(mode || '')) {
    const km = haversineKm(from, to)
    return { minutes: Math.max(2, Math.round(km / 5 * 60)), distanceKm: km, path: [from, to], source: 'walking estimate' }
  }
  const km = haversineKm(from, to)
  return { minutes: Math.max(5, Math.round(km / 50 * 60)), distanceKm: km, path: [from, to], source: 'estimated from distance' }
}

/** Airplane: "2:35" (hour:minute). Everything else: minutes, e.g. "95". */
export function formatTransitTime(minutes: number | null | undefined, mode: string): string {
  if (minutes == null || isNaN(minutes)) return ''
  const total = Math.round(minutes)
  if (isFlight(mode)) {
    const h = Math.floor(total / 60), m = total % 60
    return `${h}:${String(m).padStart(2, '0')}`
  }
  return String(total)
}

/** Parse an hour:minute string like "2:35" (or a plain number) into total minutes. */
export function parseTransitTime(value: string, mode: string): number | null {
  const v = value.trim(); if (!v) return null
  if (isFlight(mode) && v.includes(':')) {
    const [h, m] = v.split(':').map(Number)
    if (isNaN(h) || isNaN(m)) return null
    return h * 60 + m
  }
  const n = Number(v); return isNaN(n) ? null : Math.round(n)
}

/** Compact duration for in-between labels: "45m" under an hour, otherwise "2h" / "1.5h". */
export function formatCompactDuration(minutes: number | null | undefined): string {
  if (minutes == null || isNaN(minutes)) return ''
  const m = Math.round(minutes)
  if (m < 60) return `${m}m`
  const h = m / 60
  return `${Number.isInteger(h) ? h : h.toFixed(1)}h`
}

export interface GapTravel { minutes: number; type: string; icon: string; mode: string }

function gapFromMode(mode: string, minutes: number): GapTravel {
  const type =
    /air|flight|plane/i.test(mode) ? 'Flight'
      : /walk/i.test(mode) ? 'Walking'
        : /train|rail/i.test(mode) ? 'Train'
          : /bus/i.test(mode) ? 'Bus'
            : /ferry/i.test(mode) ? 'Ferry'
              : /transit|metro|subway/i.test(mode) ? 'Transit'
                : 'Driving'
  return { minutes, type, icon: modeIcon(mode), mode: type === 'Flight' ? 'Airplane' : type === 'Driving' ? 'Driving' : mode }
}

/** Estimated travel between two neighbouring stops that have no transit item between them. */
export async function estimateGapTravel(from: LatLng, to: LatLng, preferredMode?: string | null): Promise<GapTravel> {
  const km = haversineKm(from, to)
  const mode = (preferredMode || '').trim()

  if (mode) {
    if (/walk/i.test(mode)) {
      try {
        const route = await getQuickestRoute(from, to, 'Walking')
        if (route) return gapFromMode('Walking', route.minutes)
      } catch { /* fall through */ }
      return gapFromMode('Walking', Math.max(2, Math.round(km / 5 * 60)))
    }
    if (/air|flight|plane/i.test(mode)) {
      return gapFromMode('Airplane', Math.max(20, Math.round(km / 750 * 60) + 30))
    }
    if (/train|rail/i.test(mode)) {
      return gapFromMode('Train', Math.max(15, Math.round(km / 90 * 60) + 10))
    }
    if (/bus/i.test(mode)) {
      return gapFromMode('Bus', Math.max(10, Math.round(km / 35 * 60) + 5))
    }
    if (/ferry/i.test(mode)) {
      return gapFromMode('Ferry', Math.max(20, Math.round(km / 40 * 60) + 15))
    }
    if (/transit|metro|subway|public/i.test(mode)) {
      return gapFromMode('Public Transit', Math.max(8, Math.round(km / 25 * 60) + 8))
    }
    // Driving / default ground
    try {
      const route = await getQuickestRoute(from, to, 'Driving')
      if (route) return gapFromMode('Driving', route.minutes)
    } catch { /* fall through */ }
    return gapFromMode('Driving', Math.max(5, Math.round(km / 50 * 60)))
  }

  if (km <= 2) {
    try {
      const walk = await getQuickestRoute(from, to, 'Walking')
      if (walk) return gapFromMode('Walking', walk.minutes)
    } catch { /* fall through */ }
    return gapFromMode('Walking', Math.max(2, Math.round(km / 5 * 60)))
  }
  if (km > 400) return gapFromMode('Airplane', Math.max(20, Math.round(km / 750 * 60) + 30))
  const route = await getQuickestRoute(from, to, 'Car')
  if (route && route.source.includes('OSRM')) return gapFromMode('Driving', route.minutes)
  if (km > 150) return gapFromMode('Airplane', Math.max(20, Math.round(km / 750 * 60) + 30))
  return gapFromMode('Driving', Math.max(5, Math.round(km / 50 * 60)))
}

export const addMinutes = (isoLocal: string, minutes: number): string => {
  const d = new Date(isoLocal); if (isNaN(+d)) return isoLocal
  d.setMinutes(d.getMinutes() + minutes)
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`
}
